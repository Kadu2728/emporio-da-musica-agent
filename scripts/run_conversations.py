def render(scenario: dict, model: str, turns: list[tuple[str, object]]) -> str:
    lines = [
        f"# {scenario['title']}",
        "",
        f"> **What this shows:** {scenario['goal']}",
        ">",
        f"> Model: `{model}` · Simulated date/time: `{os.environ['EMPORIO_NOW']}` (America/Campo_Grande) · "
        "Generated by `scripts/run_conversations.py` (real, unedited agent output).",
        "",
    ]
    for user_text, reply in turns:
        lines += [f"**Cliente:** {user_text}", ""]
        if reply.trace:
            lines += ["<details><summary>🔧 Tool calls</summary>", ""]
            for step in reply.trace:
                lines.append(f"- `{step.name}({json.dumps(step.arguments, ensure_ascii=False)})`")
            lines += ["", "</details>", ""]
        lines += [f"**Tom:** {reply.text}", "", "---", ""]
    return "\n".join(lines)


def main() -> None:
    selected = {int(a) for a in sys.argv[1:]}
    out_dir = ROOT / "conversations"
    out_dir.mkdir(exist_ok=True)
    llm = make_llm()
    for number, scenario in enumerate(SCENARIOS, start=1):
        if selected and number not in selected:
            continue
        agent = Agent(llm, memory=ConversationStore(":memory:"))
        turns = []
        for text in scenario["turns"]:
            reply = agent.reply(scenario["slug"], text)
            turns.append((text, reply))
            print(f"[{scenario['slug']}] Cliente: {text}\n  tools: {[t.name for t in reply.trace]}\n  Tom: {reply.text}\n")
        (out_dir / f"{scenario['slug']}.md").write_text(render(scenario, llm.name, turns), encoding="utf-8")


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    main()
