"""Small routing eval: does the agent consult the right source (data vs. policy vs. nothing)?

Each case is a single customer message plus the tools that MUST be called and the tools that must
NOT be called. Writes evals/routing_results.md.

    python scripts/eval_routing.py
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
os.environ.setdefault("EMPORIO_NOW", "2026-03-24T10:30")

from dotenv import load_dotenv  # noqa: E402

load_dotenv(ROOT / ".env")

from emporio_agent.agent import Agent  # noqa: E402
from emporio_agent.llm import make_llm  # noqa: E402
from emporio_agent.memory import ConversationStore  # noqa: E402

DATA = {"search_products", "get_product_details", "list_active_promotions", "lookup_orders", "check_return_eligibility"}

# (message, must call at least one of, must not call any of, expected answer must contain any of)
CASES = [
    ("Quanto custa o Yamaha F310?", {"get_product_details", "search_products"}, {"get_store_policy"}, ["699,90"]),
    ("Tem guitarra Fender aí?", {"search_products", "get_product_details"}, set(), ["Fender"]),
    ("Quais ukuleles vocês têm até 300 reais?", {"search_products"}, set(), ["R$"]),
    ("Tem o Giannini GF-3D em estoque?", {"get_product_details", "search_products"}, set(), ["esgot", "indispon"]),
    ("Quais as promoções de hoje?", {"list_active_promotions"}, set(), ["%"]),
    ("Qual o horário de vocês no sábado?", {"get_store_policy"}, DATA, ["13"]),
    ("Qual o endereço da loja?", {"get_store_policy"}, DATA, ["14 de Maio"]),
    ("Aceitam boleto?", {"get_store_policy"}, DATA, ["oleto"]),
    ("Quanto tempo demora o SEDEX?", {"get_store_policy"}, DATA, ["2 a 5"]),
    ("Qual a garantia dos instrumentos?", {"get_store_policy"}, DATA, ["90"]),
    ("Como peço para apagarem meus dados?", {"get_store_policy"}, DATA, ["WhatsApp", "e-mail"]),
    ("Qual o status do meu pedido?", set(), DATA, ["e-mail", "telefone"]),  # must ask for identification first
    ("Pedido 10, email bruno.martins@jmail.com. Já foi enviado?", {"lookup_orders"}, set(), ["não encontr", "conferir", "confirm"]),
    ("Vocês vendem palheta?", set(), {"lookup_orders", "check_return_eligibility"}, ["instrumento"]),
    ("Me recomenda uma série boa na Netflix?", set(), DATA | {"get_store_policy"}, ["Empório", "instrument"]),
]


def main() -> None:
    llm = make_llm()
    rows, passed = [], 0
    for message, must_any, must_not, expect_any in CASES:
        agent = Agent(llm, memory=ConversationStore(":memory:"))
        reply = agent.reply("eval", message)
        called = {t.name for t in reply.trace}
        ok_must = not must_any or bool(called & must_any)
        ok_not = not (called & must_not)
        ok_text = any(e.lower() in reply.text.lower() for e in expect_any)
        ok = ok_must and ok_not and ok_text
        passed += ok
        rows.append(f"| {'✅' if ok else '❌'} | {message} | {', '.join(sorted(called)) or '—'} | {reply.text[:140].replace('|', '/').replace(chr(10), ' ')}… |")
        print(("PASS" if ok else "FAIL"), message, sorted(called))

    report = [
        "# Routing eval",
        "",
        f"Model: `{llm.name}` · **{passed}/{len(CASES)} passed** · generated by `scripts/eval_routing.py`",
        "",
        "A case passes when the agent called the expected source (data tools vs. policy manual vs. none), "
        "avoided the forbidden ones, and the answer contains the expected fact.",
        "",
        "| | Message | Tools called | Answer (truncated) |",
        "|---|---|---|---|",
        *rows,
        "",
    ]
    (ROOT / "evals").mkdir(exist_ok=True)
    (ROOT / "evals" / "routing_results.md").write_text("\n".join(report), encoding="utf-8")
    print(f"\n{passed}/{len(CASES)} passed")


if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    main()
